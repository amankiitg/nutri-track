/**
 * The broadcasts, in one list, so the test can prove each checked-in .html is this output.
 */
export const BROADCASTS = [
  {
    file: "emails/diwali-2026.html",
    title: "Happy Diwali from NutriTrack",
    preview: "A happy Diwali to you and yours. Light, good food, and the people you love.",
    headlineHtml: `Happy <em style="color: #195c2e">Diwali</em>.`,
    sections: diwaliBody(),
  },
  {
    file: "emails/thanksgiving-2026.html",
    title: "Black Friday deal: 100% off. (It was always free.)",
    preview: "No sign-up, no 5 AM lines. Happy early Thanksgiving.",
    headlineHtml: `Black Friday deal: <em style="color: #195c2e">100% off</em>.`,
    sections: blackFridayBody(),
    comment: [
      "Generated by tools/email/render.ts. Do not edit by hand: edit the copy in that script and",
      'run "npm run email:render" from the repo root.',
      "",
      "Subject: Black Friday deal: 100% off. (It was always free.)",
      "Preview: No sign-up, no 5 AM lines. Happy early Thanksgiving.",
      "From:    Aman at NutriTrack <hello@tracknutri.app>, reply-to the same (it forwards to Gmail).",
    ].join("\n      "),
  },
];

/** Each broadcast as HTML, without writing anything: what the test compares against. */
export function renderBroadcasts(): Array<{ file: string; html: string }> {
  return BROADCASTS.map((broadcast) => ({
    file: broadcast.file,
    html: renderEmail({
      title: broadcast.title,
      preview: broadcast.preview,
      sections: broadcast.sections,
      ...(broadcast.headlineHtml === undefined ? {} : { headlineHtml: broadcast.headlineHtml }),
      ...(broadcast.comment === undefined ? {} : { comment: broadcast.comment }),
    }),
  }));
}

/**
 * Writes the files, but only when run as a script. Importing this module (as the test does) must
 * not rewrite the very files that test is about to compare against.
 */
if (process.env["VITEST"] === undefined && process.argv[1]?.endsWith("render-emails.mjs")) {
  for (const broadcast of renderBroadcasts()) {
    writeFileSync(join(REPO, broadcast.file), broadcast.html);
    console.log("wrote", broadcast.file, broadcast.html.length, "bytes");
  }
}
