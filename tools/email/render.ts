/**
 * Renders the broadcast emails in `emails/` from the one layout.
 *
 * Nobody hand-writes email HTML any more: this file owns the copy, calls `renderEmail`, and
 * writes the .html beside the hand-written .txt. Run it with `npm run email:render` after any
 * copy change; `shared/email-layout.test.ts` fails if a checked-in .html does not match what this
 * script produces, so a stray hand edit cannot survive.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { renderEmail, type EmailSection } from "../../shared/email-layout";

// Run from the repo root (`npm run email:render`), which is also where the paths below point.
const REPO = process.cwd();

const TRY_BLACK_FRIDAY = "https://tracknutri.app/try?utm_source=email&utm_campaign=black_friday";

